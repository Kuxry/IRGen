# File: dataset/dataset_flickr_instance.py

import os
import pickle as pkl
import torch
import torch.utils.data
from PIL import Image
import numpy as np

class FlickrInstanceDataset(torch.utils.data.Dataset):
    """
    Dataset class for Flickr30k, treating each image as a unique instance/class.
    Loads data from a pre-processed pkl file generated by
    generate_flickr30k_gnd.py (or similar).
    """

    def __init__(self, gnd_pkl_path, image_root_dir, split='db', transform=None):
        """
        Args:
            gnd_pkl_path (str): Path to the .pkl file containing preprocessed data.
                                Expected keys for 'db' split: 'imlist', 'classes'.
            image_root_dir (str): Root directory where images are stored.
            split (str): Specifies which split to load ('db', 'query', 'val').
                         Currently, only 'db' is fully implemented for training.
            transform (callable, optional): Optional transform to be applied
                                             on a sample.
        """
        self.gnd_pkl_path = gnd_pkl_path
        self.image_root_dir = image_root_dir
        self.split = split
        self.transform = transform
        self._db = []
        self._num_classes = 0

        # Check if paths exist
        if not os.path.exists(self.gnd_pkl_path):
             raise FileNotFoundError(f"GND PKL file not found at: {self.gnd_pkl_path}")
        if not os.path.exists(self.image_root_dir):
             raise FileNotFoundError(f"Image root directory not found at: {self.image_root_dir}")

        self._construct_db()

    def _construct_db(self):
        """Loads the database from the pkl file based on the split."""
        try:
            with open(self.gnd_pkl_path, 'rb') as f:
                gnd_data = pkl.load(f)
        except Exception as e:
            raise IOError(f"Error loading GND PKL file {self.gnd_pkl_path}: {e}")

        print(f"Loading '{self.split}' split from {self.gnd_pkl_path}...")

        if self.split == 'db':
            if 'imlist' not in gnd_data or 'classes' not in gnd_data:
                raise ValueError(f"PKL file must contain 'imlist' and 'classes' keys for 'db' split.")

            imlist = gnd_data['imlist']
            # 'classes' should be the instance indices [0, 1, ..., N-1]
            classes = gnd_data['classes']

            if len(imlist) != len(classes):
                raise ValueError("Length of 'imlist' and 'classes' must match in PKL file.")

            self._num_classes = len(imlist) # For instance discrimination, num_classes = num_images

            for i in range(len(imlist)):
                im_fn = imlist[i]
                # Construct the full image path
                # Handle potential subdirectories if im_fn includes them,
                # otherwise assume flat structure in image_root_dir.
                im_path = os.path.join(self.image_root_dir, im_fn)

                # Class label is the instance index itself
                class_label = classes[i]

                self._db.append({
                    "im_path": im_path,
                    "class": int(class_label), # Ensure class is an integer
                    "idx": i # The index within this dataset split
                })
            print(f"Loaded {len(self._db)} images for 'db' split.")

        # Add logic for 'query' or 'val' splits if needed for evaluation later
        # For now, tokenizer training only needs 'db'
        elif self.split == 'query':
             print("Warning: 'query' split loading not fully implemented for returning labels/indices yet.")
             qimlist = gnd_data.get('qimlist', [])
             for i, im_fn in enumerate(qimlist):
                 im_path = os.path.join(self.image_root_dir, im_fn)
                 self._db.append({"im_path": im_path, "idx": i}) # Only path and index for now
             print(f"Loaded {len(self._db)} image paths for 'query' split.")

        elif self.split == 'val':
             print("Warning: 'val' split loading not fully implemented for returning labels/indices yet.")
             val_imlist = gnd_data.get('val_imlist', [])
             for i, im_fn in enumerate(val_imlist):
                  im_path = os.path.join(self.image_root_dir, im_fn)
                  self._db.append({"im_path": im_path, "idx": i}) # Only path and index for now
             print(f"Loaded {len(self._db)} image paths for 'val' split.")

        else:
            print(f"Warning: Split '{self.split}' not recognized or handled. Database is empty.")

    def __getitem__(self, index):
        """
        Args:
            index (int): Index

        Returns:
            tuple: (image, class_label, index) for 'db' split.
                   (image) or other format for other splits (needs implementation).
        """
        if index >= len(self._db):
            raise IndexError(f"Index {index} out of bounds for dataset split '{self.split}' with length {len(self._db)}")

        db_entry = self._db[index]
        im_path = db_entry["im_path"]

        try:
            # Load image
            im = Image.open(im_path).convert('RGB')
        except FileNotFoundError:
            print(f"Error: Image file not found at {im_path}")
            # Return dummy data or raise error
            # For robustness, maybe return None or skip? Returning dummy for now.
            # Ideally, ensure pkl file only lists existing images.
            dummy_im = torch.zeros((3, 224, 224)) # Assuming 224x224 input size
            if self.split == 'db':
                 return dummy_im, -1, index # Return dummy class -1
            else:
                 return dummy_im
        except Exception as e:
            print(f"Error loading image {im_path}: {e}")
            dummy_im = torch.zeros((3, 224, 224))
            if self.split == 'db':
                 return dummy_im, -1, index
            else:
                 return dummy_im

        # Apply transform
        if self.transform:
            im = self.transform(im)

        # Return data based on split
        if self.split == 'db':
            # Ensure class and idx are present for 'db' split
            class_label = db_entry.get('class', -1) # Default to -1 if missing
            idx = db_entry.get('idx', index)
            return im, class_label, idx
        else:
            # For query/val, just return image for now (adjust if needed later)
            return im

    def __len__(self):
        """Return the number of samples in the dataset."""
        return len(self._db)

    def get_num_classes(self):
        """Return the number of classes (unique instances for 'db' split)."""
        if self.split == 'db':
            return self._num_classes
        else:
            # Number of classes is typically only relevant for the training set
            return 0